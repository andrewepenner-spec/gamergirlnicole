import asyncio
from pathlib import Path
from playwright.async_api import async_playwright

async def main():
 async with async_playwright() as p:
  browser=await p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
  ctx=await browser.new_context(viewport={'width':1480,'height':980},device_scale_factor=1)
  page=await ctx.new_page()
  errors=[]
  page.on('pageerror',lambda exc:errors.append(str(exc)))
  await page.goto('http://127.0.0.1:8000/',wait_until='networkidle')
  await page.screenshot(path='/mnt/data/clue_rebuilt/docs/screenshot-landing.png',full_page=True)
  print('LANDING H1:',await page.locator('h1').all_text_contents())
  await page.locator('#create-name').fill('Ada')
  await page.get_by_role('button',name='Create new room').click()
  await page.wait_for_selector('.roster-row')
  print('ROOM CREATED',await page.locator('.room-tag').inner_text())
  roomcode=(await page.locator('.room-tag').inner_text()).split()[1]
  await page.screenshot(path='/mnt/data/clue_rebuilt/docs/screenshot-lobby.png',full_page=True)
  guest=await browser.new_context(viewport={'width':425,'height':900},device_scale_factor=1)
  gp=await guest.new_page()
  gp.on('pageerror',lambda exc:errors.append('guest '+str(exc)))
  await gp.goto('http://127.0.0.1:8000/',wait_until='networkidle')
  await gp.locator('#join-code').fill(roomcode)
  await gp.locator('#join-name').fill('Byron')
  await gp.get_by_role('button',name='Join existing investigation').click()
  await gp.wait_for_selector('.roster-row')
  print('GUEST JOINED',await gp.locator('.roster-row').count())
  await gp.screenshot(path='/mnt/data/clue_rebuilt/docs/screenshot-phone-lobby.png',full_page=True)
  await page.reload(wait_until='networkidle')
  await page.get_by_role('button',name='Begin the investigation').click()
  await page.wait_for_selector('.identity-seal')
  print('IDENTITY:',await page.locator('.private-id h1').inner_text())
  await page.screenshot(path='/mnt/data/clue_rebuilt/docs/screenshot-identity.png',full_page=True)
  await page.get_by_role('button',name='Begin Scene 1').click()
  await page.wait_for_selector('.film-view')
  await page.screenshot(path='/mnt/data/clue_rebuilt/docs/screenshot-scene.png',full_page=True)
  await page.get_by_role('button',name='Finish scene').click()
  await page.wait_for_selector('[data-reveal]')
  await page.locator('[data-reveal="0"]').click()
  await gp.reload(wait_until='networkidle')
  await gp.locator('[data-nav="identity"]').click()
  await gp.locator('[data-reveal="0"]').click()
  await page.reload(wait_until='networkidle')
  await page.locator('[data-nav="cards"]').click()
  await page.wait_for_selector('.playing-card')
  await page.screenshot(path='/mnt/data/clue_rebuilt/docs/screenshot-cards.png',full_page=True)
  await page.locator('[data-nav="notebook"]').click()
  await page.screenshot(path='/mnt/data/clue_rebuilt/docs/screenshot-notebook.png',full_page=True)
  print('ERRORS:',errors)
  await browser.close()

asyncio.run(main())
